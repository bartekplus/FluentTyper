/** The generated rule modules: the code of each rule file. */
const RULES_OUT = path.join(ENGINE_DIR, "rules");
/** The folder of each language with Review data: its phrase tables ship in that data. */
const DATA_FOLDERS: Record<(typeof REVIEW_DATA_LANGUAGES)[number], string> = {
  ar: "arabic",
  de: "german",
  es: "spanish",
  fr: "french",
  pl: "polish",
  pt: "portuguese",
  sv: "swedish",
};
const isDataLanguage = (lang: string) =>
  (REVIEW_DATA_LANGUAGES as readonly string[]).includes(lang);
const HEADER =
  "// Generated by bun scripts/compile-grammar-rules.ts from grammar/rules/*.yaml. Do not edit.\n";

/**
 * The names the rule library exports, read from its text: importing it would load the Review
 * modules, which import the generated modules this script writes. It re-exports by name only.
 */
export async function readLibrary(): Promise<{ values: Set<string>; types: Set<string> }> {
  const text = await readFile(LIBRARY, "utf8");
  const values = new Set<string>();
  const types = new Set<string>();
  const names = (list: string) =>
    list
      .split(",")
      .map((part) =>
        part
          .trim()
          .split(/\s+as\s+/)
          .pop()!,
      )
      .filter(Boolean);
  for (const m of text.matchAll(/export\s+(type\s+)?\{([^}]*)\}/g))
    for (const name of names(m[2])) (m[1] ? types : values).add(name);
  for (const m of text.matchAll(/export\s+(?:type|interface)\s+([A-Za-z_$][\w$]*)/g))
    types.add(m[1]);
  for (const m of text.matchAll(/export\s+(?:const|function)\s+([A-Za-z_$][\w$]*)/g))
    values.add(m[1]);
  if (/export\s+\*/.test(text)) throw new Error("library.ts: re-export names one by one");
  return { values, types };
}

/** Reads and compiles every rule file. */
export async function compileGrammarRules(): Promise<CompiledRuleSet> {
  const files = await Promise.all(
    RULE_FILES.map(async (name) => {
      const text = await readFile(path.join(RULES_DIR, `${name}.yaml`), "utf8");
      const parsed = (Bun.YAML.parse(text) ?? {}) as RuleFile;
      return [name, parsed] as const;
    }),
  );
  const { values } = await readLibrary();
  const set = compileRuleFiles(files, { library: values });
  return set;
}

const json = (value: unknown) => JSON.stringify(value);

/**
 * The catalog module, as compact as the hand-written catalog was: content scripts load it.
 * A Review-only check with the default keys is a reviewOnly() call, a supported check's
 * metadata is a supported() call, and a language list used twice is one constant.
 */
function catalogModule(set: CompiledRuleSet): string {
  const lists = new Map<string, string>();
  const counts = new Map<string, number>();
  for (const metadata of Object.values(set.reviewMetadata))
    if (metadata.review === "supported" && metadata.languages) {
      const key = json(metadata.languages);
      counts.set(key, (counts.get(key) ?? 0) + 1);
    }
  for (const [key, count] of counts) if (count > 1) lists.set(key, `LANGUAGES_${lists.size}`);

  const entries = set.catalog.map((entry) => {
    const plain =
      entry.typing === false &&
      entry.titleI18nKey === `grammar_rule_${entry.id}` &&
      entry.descriptionI18nKey === `grammar_rule_${entry.id}_desc` &&
      entry.codeSafe === undefined;
    if (!plain) return json(entry);
    const scope = entry.languageScope === "all" ? "" : `, ${json(entry.languageScope)}`;
    return `reviewOnly(${json(entry.id)}, ${entry.priority}${scope})`;
  });
  const metadata = Object.entries(set.reviewMetadata).map(([id, value]) => {
    if (value.review === "excluded") return `${id}: ${json(value)} as const`;
    const extra = [
      value.note === undefined ? "" : `note: ${json(value.note)}`,
      value.languages === undefined
        ? ""
        : `languages: ${lists.get(json(value.languages)) ?? json(value.languages)}`,
    ].filter(Boolean);
    const options = extra.length ? `, { ${extra.join(", ")} }` : "";
    return `${id}: supported(${json(value.category)}, ${json(value.kind)}, ${value.bulk === "eligible"}, ${value.defaultEnabled}${options})`;
  });
  // ruleCatalog.ts types the catalog: GrammarRuleId is derived from it, so no satisfies here.
  return `${HEADER}
/** A Review-only check whose settings keys follow its id. */
function reviewOnly<const Id extends string>(
  id: Id,
  priority: number,
  languageScope: "all" | "en_US" = "all",
) {
  return {
    id,
    typing: false as const,
    titleI18nKey: \`grammar_rule_\${id}\` as const,
    descriptionI18nKey: \`grammar_rule_\${id}_desc\` as const,
    languageScope,
    priority,
  };
}

export const CATALOG = [${entries.join(",\n")}] as const;

export type GeneratedCatalogRuleId = (typeof CATALOG)[number]["id"];

/** The typing rules: checks with mode "live". */
export type GeneratedGrammarRuleId = Exclude<
  (typeof CATALOG)[number],
  { typing: false }
>["id"];

export const EXCLUSIVE_GROUPS: readonly (readonly GeneratedCatalogRuleId[])[] = ${json(set.exclusive)};

${[...lists].map(([list, name]) => `const ${name} = ${list} as const;`).join("\n")}

/** The metadata of a check Review runs. */
function supported<const Category extends string, const Kind extends string>(
  category: Category,
  kind: Kind,
  safeToFix: boolean,
  defaultEnabled: boolean,
  extra: { note?: string; languages?: readonly string[] } = {},
) {
  return {
    review: "supported" as const,
    defaultEnabled,
    category,
    kind,
    bulk: safeToFix ? ("eligible" as const) : ("individual" as const),
    ...extra,
  };
}

export const REVIEW_METADATA = {
${metadata.join(",\n")}
};

export const PHRASE_TABLE_KINDS = ${json(set.phraseTableKinds)} as const;
`;
}

function copyModule(set: CompiledRuleSet): string {
  return `${HEADER}import type { CheckExampleOut } from "./compiler";

/** Settings copy of the checks: i18n key -> UI language -> text. Only the options page loads it. */
export const CHECK_TEXT: Readonly<Record<string, Readonly<Record<string, string>>>> = ${json(set.text)};

/** The settings example of each check. */
export const CHECK_EXAMPLES: Readonly<Record<string, CheckExampleOut>> = ${json(set.examples)};
`;
}

function liveModule(set: CompiledRuleSet): string {
  return `${HEADER}import type { PatternSet } from "./matcher";

/** Typing checks in priority order: a named implementation or live patterns. */
export const LIVE_RULES: readonly {
  check: string;
  predicate?: string;
  patterns: readonly number[];
}[] = ${json(set.live)};

export const LIVE_PATTERNS: PatternSet = ${json(set.livePatterns)};
`;
}

const rowText = (rows: readonly PhraseRow[]) =>
  rows
    .map(([typed, fix]) => `${[typed].flat().join(" | ")} = ${[fix].flat().join("; ")}`)
    .join("\n");

/** A language's phrase tables as Review data strings (review-data/<lang>.json). */
function phraseDataModule(tables: CompiledRuleSet["phrases"][string]): string {
  const exports = Object.entries(tables).map(
    ([kind, rows]) => `export const PHRASES_${kind.toUpperCase()} = ${json(rowText(rows!))};`,
  );
  return `${HEADER}// The phrase tables of the language: Review data, loaded before its first check.\n${exports.join("\n\n")}\n`;
}

function reviewModule(set: CompiledRuleSet): string {
  return `${HEADER}import type { CompiledFrame, CompiledRule } from "./types";
import type { PatternSet } from "./matcher";
import type { PhraseRow } from "./compiler";

/** Review rules in evaluation order. */
export const REVIEW_RULES: readonly CompiledRule[] = ${json(set.rules)};

export const REVIEW_PATTERNS: PatternSet = ${json(set.reviewPatterns)};

// Each frame is typed on its own: one array literal of thousands of frame shapes makes a union
// type too complex for the type checker (TS2590).
const frame = (value: CompiledFrame): CompiledFrame => value;

/** The frames of the frame rules, with their prefilter literals. */
export const REVIEW_FRAMES: readonly CompiledFrame[] = [${set.frames.map((value) => `frame(${json(value)})`).join(",\n")}];

/** Phrase tables of the languages without Review data, by two-letter language and kind. */
export const PHRASES: Readonly<Record<string, Readonly<Record<string, readonly PhraseRow[]>>>> = ${json(
    Object.fromEntries(Object.entries(set.phrases).filter(([lang]) => !isDataLanguage(lang))),
  )};

/** Named phrase tables: "<file>.<name>". */
export const TABLES: Readonly<Record<string, readonly PhraseRow[]>> = ${json(set.tables)};
`;
}

// The parameter types and the result type of a generated fixer, by frame style.
const PARAM_TYPES: Readonly<Record<string, string>> = {
  m: "RegExpExecArray",
  ctx: "DetectContext",
  frame: "FrameRef",
  target: "string",
};
const RESULTS: Readonly<Record<FrameStyle, string>> = {
  frame: "string | readonly string[] | null",
  template: "string",
  slot: "FixResult",
  carry: "string | readonly string[] | null",
  german: "string | readonly string[] | null",
  portuguese: "readonly string[]",
  cased: "string",
  polish: "string | readonly string[] | null",
  comma: "string | null",
  swap: "string | null",
  match: "MatchResult",
};

/** The TypeScript type of a YAML value of a map. */
function tsType(value: unknown): string {
  if (value === null) return "null";
  if (Array.isArray(value)) {
    const items = [...new Set(value.map(tsType))];
    return `readonly (${items.length ? items.join(" | ") : "never"})[]`;
  }
  if (typeof value === "object") {
    const items = [...new Set(Object.values(value).map(tsType))];
    return `Readonly<Record<string, ${items.length ? items.join(" | ") : "never"}>>`;
  }
  return typeof value;
}

/** A condition that ends a body: "when x" ends it when x fails ("when !x" when x holds). */
const failing = (source: string) => {
  const { negated } = checkExpression(source);
  return negated ?? `!(${source})`;
};

const bodyLines = (steps: readonly CodeStep[], result: string, otherwise: string) => [
  ...steps.map((step) =>
    step.kind === "let"
      ? `const ${step.name} = ${step.source};`
      : `if (${failing(step.source)}) return ${otherwise};`,
  ),
  `return ${result};`,
];

/** The generated module of one rule file: its sets, maps, defs and frame fixers. */
function ruleModule(
  name: string,
  code: FileCode,
  library: { values: Set<string>; types: Set<string> },
  shared: ReadonlySet<string>,
): string {
  const common = name === "common";
  // Every name is exported: Review code that is not yet in a rule file may read a set or a def.
  const out = "export ";
  const parts: string[] = [];
  const sources: string[] = [];
  const typeText: string[] = [];
  for (const [key, words] of Object.entries(code.sets))
    parts.push(`${out}const ${key}: ReadonlySet<string> = new Set(${json(words)});`);
  for (const [key, map] of Object.entries(code.maps))
    parts.push(`${out}const ${key}: ${tsType(map)} = ${json(map)};`);
  for (const def of code.defs) {
    sources.push(def.result, def.otherwise, ...def.steps.map((step) => step.source));
    if (def.args === undefined) {
      parts.push(`// ${def.where}\n${out}const ${def.name} = ${def.result};`);
      continue;
    }
    typeText.push(def.args, def.type ?? "");
    const lines = bodyLines(def.steps, def.result, def.otherwise);
    parts.push(
      `// ${def.where}\n${out}function ${def.name}(${def.args})${def.type ? `: ${def.type}` : ""} {\n${lines.join("\n")}\n}`,
    );
  }
  const fixers = code.frames.map((frame) => {
    sources.push(frame.fix, ...frame.steps.map((step) => step.source));
    const params = frame.params.map((param) => `${param}: ${PARAM_TYPES[param]}`);
    typeText.push(...frame.params.map((param) => PARAM_TYPES[param]), RESULTS[frame.style]);
    const lines = [
      ...frame.groups.map((group) => `const ${group} = m.groups!.${group};`),
      ...bodyLines(frame.steps, frame.fix, frame.style === "portuguese" ? "[]" : "null"),
    ];
    return `// ${frame.where}\n${json(frame.key)}: (${params.join(", ")}): ${RESULTS[frame.style]} => {\n${lines.join("\n")}\n}`;
  });
  // The library and shared names the code reads, and the library types its text names.
  const refs = new Set<string>();
  for (const source of sources) for (const ref of checkExpression(source).refs) refs.add(ref);
  const words = new Set(`${sources.join(" ")} ${typeText.join(" ")}`.match(/[A-Za-z_$][\w$]*/g));
  const values = [...refs].filter((ref) => library.values.has(ref)).sort();
  const types = [...library.types].filter((type) => words.has(type)).sort();
  const fromCommon = common ? [] : [...refs].filter((ref) => shared.has(ref)).sort();
  const imports = [
    `import type { AnyFixer } from "../reviewRules";`,
    types.length ? `import type { ${types.join(", ")} } from "../../library";` : "",
    values.length ? `import { ${values.join(", ")} } from "../../library";` : "",
    fromCommon.length ? `import { ${fromCommon.join(", ")} } from "./common.generated";` : "",
  ].filter(Boolean);
  return `${HEADER}// The code of grammar/rules/${name}.yaml: its sets, maps, defs and the fixes of its frames.
${imports.join("\n")}

${parts.join("\n\n")}

/** The frame fixes of the file, by the name its compiled frames give ("@<rule id>/<frame>"). */
export const FIXERS: Readonly<Record<string, AnyFixer>> = {
${fixers.join(",\n")}
};
`;
}

/** The index of the generated rule modules: their fixers by rule file. */
function ruleIndexModule(names: readonly string[]): string {
  return `${HEADER}import type { AnyFixer } from "../reviewRules";
${names.map((name) => `import { FIXERS as ${name} } from "./${name}.generated";`).join("\n")}

/** The frame fixes of the rule files' expressions, by rule file and name. */
export const RULE_FIXERS: Readonly<Record<string, Readonly<Record<string, AnyFixer>>>> = {
  ${names.join(", ")}
};
`;
}

/** The generated modules, formatted: absolute path -> content. */
export async function generateGrammarRuleModules(): Promise<Record<string, string>> {
  const set = await compileGrammarRules();
  const library = await readLibrary();
  const names = Object.keys(set.code);
  const shared = set.code.common?.names ?? new Set<string>();
  const modules: Record<string, string> = {
    "catalog.generated.ts": catalogModule(set),
    "copy.generated.ts": copyModule(set),
    "live.generated.ts": liveModule(set),
    "review.generated.ts": reviewModule(set),
  };
  for (const name of names)
    modules[path.join(RULES_OUT, `${name}.generated.ts`)] = ruleModule(
      name,
      set.code[name],
      library,
      shared,
    );
  modules[path.join(RULES_OUT, "index.generated.ts")] = ruleIndexModule(names);
  for (const [lang, folder] of Object.entries(DATA_FOLDERS))
    modules[path.join(REVIEW_DIR, folder, "phrases.generated.ts")] = phraseDataModule(
      set.phrases[lang] ?? {},
    );
  const out: Record<string, string> = {};
  for (const [name, source] of Object.entries(modules)) {
    const file = path.resolve(ENGINE_DIR, name);
    const options = (await resolveConfig(file)) ?? {};
    out[file] = await format(source, { ...options, filepath: file });
  }
  return out;
}

/** Writes the generated modules that are not current; returns their paths. */
export async function writeGrammarRuleModules(): Promise<string[]> {
  const written: string[] = [];
  for (const [file, content] of Object.entries(await generateGrammarRuleModules())) {
    if ((await readFile(file, "utf8").catch(() => "")) === content) continue;
    await Bun.write(file, content);
    written.push(file);
  }
  return written;
}
