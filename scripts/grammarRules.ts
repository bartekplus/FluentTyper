/**
 * The source of a YAML map: a table with no prototype (wordTable), also for a nested map, so that
 * a typed word such as "constructor" finds no Object member.
 */
function tableSource(value: unknown): string {
  if (typeof value !== "object" || value === null || Array.isArray(value)) return json(value);
  const entries = Object.entries(value).map(([key, item]) => `${json(key)}: ${tableSource(item)}`);
  return `wordTable({ ${entries.join(", ")} })`;
}

/** The TypeScript type of a YAML value of a map. */
function tsType(value: unknown): string {
  if (value === null) return "null";
  if (Array.isArray(value)) {
    const items = [...new Set(value.map(tsType))];
    return `readonly (${items.length ? items.join(" | ") : "never"})[]`;
  }
  if (typeof value === "object") {
    const items = [...new Set(Object.values(value).map(tsType))];
    return `Readonly<Record<string, ${items.length ? items.join(" | ") : "never"}>>`;
  }
  return typeof value;
}

/** A condition that ends a body: "when x" ends it when x fails ("when !x" when x holds). */
const failing = (source: string) => {
  const { negated } = checkExpression(source);
  return negated ?? `!(${source})`;
};

const bodyLines = (steps: readonly CodeStep[], result: string, otherwise: string) => [
  ...steps.map((step) =>
    step.kind === "let"
      ? `const ${step.name} = ${step.source};`
      : `if (${failing(step.source)}) return ${otherwise};`,
  ),
  `return ${result};`,
];

/** The source of one function of a rule file. */
function functionSource(fn: FunctionCode): { text: string; types: string[] } {
  const portuguese = fn.style === "portuguese";
  const all = portuguese ? PORTUGUESE_PARAMS : PARAMS[fn.kind];
  const params = all.slice(0, fn.params.length).map(([param, type]) => `${param}: ${type}`);
  const result = fn.kind === "fixer" ? RESULTS[fn.style ?? "frame"] : KIND_RESULTS[fn.kind];
  const lines = [
    ...fn.groups.map((group) => `const ${group} = m.groups!.${group};`),
    ...bodyLines(fn.steps, fn.result, fn.otherwise),
  ];
  const arrow = `(${params.join(", ")}): ${result} => {\n${lines.join("\n")}\n}`;
  const text =
    fn.kind === "live" ? `{ triggers: ${json(fn.triggers ?? [])}, apply: ${arrow} }` : arrow;
  return {
    text: `// ${fn.where}\n${json(fn.key)}: ${text}`,
    types: [...params, result],
  };
}

/**
 * The names of a file that its typing rules read, also through its defs: the content scripts
 * load those and the typing rules only (`<file>.live.generated.ts`), not the Review code.
 */
function liveNames(code: FileCode): Set<string> {
  const found = new Set<string>();
  const defs = new Map(code.defs.map((def) => [def.name, def]));
  const visit = (names: readonly string[]) => {
    for (const name of names) {
      if (!code.names.has(name) || found.has(name)) continue;
      found.add(name);
      const def = defs.get(name);
      if (def) visit(def.free);
    }
  };
  for (const fn of code.functions) if (fn.kind === "live") visit(fn.free);
  return found;
}

/** A generated module: the given sets, maps, defs and functions of one rule file. */
function codeModule(
  title: string,
  name: string,
  code: FileCode,
  own: (name: string) => boolean,
  kinds: readonly CodeKind[],
  library: Library,
  shared: ReadonlySet<string>,
  fromLive: ReadonlySet<string>,
): string {
  const common = name === "common";
  // Every name is exported: Review code that is not yet in a rule file may read a set or a def.
  const out = "export ";
  const parts: string[] = [];
  const sources: string[] = [];
  const typeText: string[] = [];
  const free: string[] = [];
  for (const [key, words] of Object.entries(code.sets))
    if (own(key)) parts.push(`${out}const ${key}: ReadonlySet<string> = new Set(${json(words)});`);
  for (const [key, map] of Object.entries(code.maps))
    if (own(key)) parts.push(`${out}const ${key}: ${tsType(map)} = ${tableSource(map)};`);
  for (const def of code.defs) {
    if (!own(def.name)) continue;
    sources.push(def.result, def.otherwise, ...def.steps.map((step) => step.source));
    free.push(...def.free);
    if (def.args === undefined) {
      parts.push(`// ${def.where}\n${out}const ${def.name} = ${def.result};`);
      continue;
    }
    typeText.push(def.args, def.type ?? "");
    const lines = bodyLines(def.steps, def.result, def.otherwise);
    parts.push(
      `// ${def.where}\n${out}function ${def.name}(${def.args})${def.type ? `: ${def.type}` : ""} {\n${lines.join("\n")}\n}`,
    );
  }
  const records = new Map<CodeKind, string[]>();
  for (const fn of code.functions) {
    if (!kinds.includes(fn.kind)) continue;
    sources.push(fn.result, fn.otherwise, ...fn.steps.map((step) => step.source));
    free.push(...fn.free);
    const { text, types } = functionSource(fn);
    typeText.push(...types);
    records.set(fn.kind, [...(records.get(fn.kind) ?? []), text]);
  }
  // The names the code reads from outside the module: the file's names in its live module, the
  // library (each name from its file) and common.yaml. The file's own names hide the others.
  const refs = new Set(free.filter((ref) => !(code.names.has(ref) && own(ref))));
  // A module with maps builds them with the library's wordTable.
  if (Object.keys(code.maps).some(own)) refs.add("wordTable");
  const live = [...refs].filter((ref) => fromLive.has(ref)).sort();
  const outside = [...refs].filter((ref) => !code.names.has(ref));
  const words = new Set(`${sources.join(" ")} ${typeText.join(" ")}`.match(/[A-Za-z_$][\w$]*/g));
  const byFile = new Map<string, { values: string[]; types: string[] }>();
  const add = (from: string, kind: "values" | "types", ref: string) => {
    const entry = byFile.get(from) ?? { values: [], types: [] };
    entry[kind].push(ref);
    byFile.set(from, entry);
  };
  for (const ref of outside)
    if (library.values.has(ref)) add(library.values.get(ref)!, "values", ref);
  for (const [type, from] of library.types) if (words.has(type)) add(from, "types", type);
  const fromCommon = common
    ? []
    : outside.filter((ref) => shared.has(ref) && !library.values.has(ref)).sort();
  const records_ = kinds.filter((kind) => kind !== "live" || records.has("live"));
  const engineTypes = records_.filter((kind) => kind !== "live").map((kind) => RECORDS[kind][1]);
  const imports = [
    engineTypes.length
      ? `import type { ${engineTypes.join(", ")} } from "../../engine/reviewRules";`
      : "",
    records_.includes("live") ? `import type { LiveCode } from "../../engine/liveRules";` : "",
    ...[...byFile]
      .sort(([a], [b]) => a.localeCompare(b))
      .flatMap(([from, { values, types }]) => [
        types.length ? `import type { ${types.sort().join(", ")} } from "${from}";` : "",
        values.length ? `import { ${values.sort().join(", ")} } from "${from}";` : "",
      ]),
    fromCommon.length ? `import { ${fromCommon.join(", ")} } from "./common.generated";` : "",
    live.length ? `import { ${live.join(", ")} } from "./${name}.live.generated";` : "",
    // The main module also exports the names of its live module.
    fromLive.size && kinds.includes("fixer")
      ? `export { ${[...fromLive].sort().join(", ")} } from "./${name}.live.generated";`
      : "",
  ].filter(Boolean);
  const exports = records_.map((kind) => {
    const [record, type, doc] = RECORDS[kind];
    return `/** ${doc} */\nexport const ${record}: Readonly<Record<string, ${type}>> = {\n${(records.get(kind) ?? []).join(",\n")}\n};`;
  });
  return `${HEADER}// ${title}
${imports.join("\n")}

${parts.join("\n\n")}

${exports.join("\n\n")}
`;
}

/** The generated modules of one rule file: its Review code, and its typing rules apart. */
function ruleModules(
  name: string,
  code: FileCode,
  library: Library,
  shared: ReadonlySet<string>,
): Record<string, string> {
  const live = liveNames(code);
  const hasLive = code.functions.some((fn) => fn.kind === "live");
  const modules: Record<string, string> = {
    [`${name}.generated.ts`]: codeModule(
      `The Review code of grammar/rules/${name}.yaml: its sets, maps, defs and functions.`,
      name,
      code,
      (n) => !live.has(n),
      ["fixer", "filter", "detector"],
      library,
      shared,
      live,
    ),
  };
  if (hasLive)
    modules[`${name}.live.generated.ts`] = codeModule(
      `The typing rules of grammar/rules/${name}.yaml and the names they read: the content scripts load this module only.`,
      name,
      code,
      (n) => live.has(n),
      ["live"],
      library,
      shared,
      new Set(),
    );
  return modules;
}

/** The index of the generated Review modules: their functions by rule file. */
function ruleIndexModule(names: readonly string[]): string {
  const records = (["fixer", "filter", "detector"] as const).map((kind) => RECORDS[kind]);
  return `${HEADER}import type { AnyFixer, Detector, FindingsFilter } from "../../engine/reviewRules";
${names.map((name) => `import * as ${name} from "./${name}.generated";`).join("\n")}

${records
  .map(
    ([record, type]) =>
      `export const RULE_${record}: Readonly<Record<string, Readonly<Record<string, ${type}>>>> = {\n${names.map((name) => `${name}: ${name}.${record}`).join(",\n")}\n};`,
  )
  .join("\n\n")}
`;
}

/** The index of the typing rules with code: the content scripts load it, not the Review code. */
function liveIndexModule(names: readonly string[]): string {
  return `${HEADER}import type { LiveCode } from "../../engine/liveRules";
${names.map((name) => `import { LIVE as ${name} } from "./${name}.live.generated";`).join("\n")}

/** The typing rules with code, by rule file and name ("@<rule id>"). */
export const RULE_LIVE: Readonly<Record<string, Readonly<Record<string, LiveCode>>>> = {
  ${names.join(", ")}
};
`;
}

/** The generated modules, formatted: absolute path -> content. */
export async function generateGrammarRuleModules(): Promise<Record<string, string>> {
  const set = await compileGrammarRules();
  const library = await readLibrary();
  const names = Object.keys(set.code);
  const shared = set.code.common?.names ?? new Set<string>();
  const modules: Record<string, string> = {
    "catalog.generated.ts": catalogModule(set),
    "copy.generated.ts": copyModule(set),
    "live.generated.ts": liveModule(set),
    "review.generated.ts": reviewModule(set),
  };
  for (const name of names)
    for (const [file, source] of Object.entries(ruleModules(name, set.code[name], library, shared)))
      modules[path.join(RULES_OUT, file)] = source;
  modules[path.join(RULES_OUT, "index.generated.ts")] = ruleIndexModule(names);
  modules[path.join(RULES_OUT, "live-index.generated.ts")] = liveIndexModule(
    names.filter((name) => set.code[name].functions.some((fn) => fn.kind === "live")),
  );
  for (const [lang, folder] of Object.entries(DATA_FOLDERS))
    modules[path.join(REVIEW_DIR, folder, "phrases.generated.ts")] = phraseDataModule(
      set.phrases[lang] ?? {},
    );
  const out: Record<string, string> = {};
  for (const [name, source] of Object.entries(modules)) {
    const file = path.resolve(ENGINE_DIR, name);
    const options = (await resolveConfig(file)) ?? {};
    out[file] = await format(source, { ...options, filepath: file });
  }
  return out;
}

/** Writes the generated modules that are not current; returns their paths. */
export async function writeGrammarRuleModules(): Promise<string[]> {
  const written: string[] = [];
  for (const [file, content] of Object.entries(await generateGrammarRuleModules())) {
    if ((await readFile(file, "utf8").catch(() => "")) === content) continue;
    await Bun.write(file, content);
    written.push(file);
  }
  return written;
}
