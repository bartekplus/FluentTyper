/** "την"/"τη" by the next word's first sound (see phonology.ts). */
const nu = (word: string, next: string) => (keepsFinalNu(next) ? `${word}ν` : word);

function feminineRows(): PhraseRow[] {
  const rows: PhraseRow[] = [];
  for (const line of FEMININE_OS) {
    const [nom, gen, acc, nomPl, , accPl] = line.split(" ");
    rows.push(
      [`ο ${nom}`, `η ${nom}`],
      [`ένας ${nom}`, `μια ${nom}`],
      [`αυτός ο ${nom}`, `αυτή η ${nom}`],
      [`${nom} αυτός`, `${nom} αυτή`],
      [`του ${gen}`, `της ${gen}`],
      [`αυτού του ${gen}`, `αυτής της ${gen}`],
      [[`τον ${acc}`, `το ${acc}`], `${nu("τη", acc)} ${acc}`],
      [[`στον ${acc}`, `στο ${acc}`], `${nu("στη", acc)} ${acc}`],
      [`έναν ${acc}`, `μια ${acc}`],
      [`αυτόν τον ${acc}`, `αυτή ${nu("τη", acc)} ${acc}`],
    );
    if (!nomPl) continue;
    rows.push(
      [`αυτοί οι ${nomPl}`, `αυτές οι ${nomPl}`],
      [`${nomPl} αυτοί`, `${nomPl} αυτές`],
      [`όλοι οι ${nomPl}`, `όλες οι ${nomPl}`],
      [`πολλοί ${nomPl}`, `πολλές ${nomPl}`],
      [`διάφοροι ${nomPl}`, `διάφορες ${nomPl}`],
      [`κάποιοι ${nomPl}`, `κάποιες ${nomPl}`],
      [`τους ${accPl}`, `τις ${accPl}`],
      [`στους ${accPl}`, `στις ${accPl}`],
      [`όλους τους ${accPl}`, `όλες τις ${accPl}`],
      [`αυτούς τους ${accPl}`, `αυτές τις ${accPl}`],
      [`πολλούς ${accPl}`, `πολλές ${accPl}`],
      [[`διάφορους ${accPl}`, `διαφόρους ${accPl}`], `διάφορες ${accPl}`],
    );
  }
  return rows;
}

